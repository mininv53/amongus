const LANG_ORDER = ['en', 'ru', 'ro'];
const LANG_LABELS = { en: 'EN', ru: 'RU', ro: 'RO' };

const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    return localStorage.getItem('deepguard_lang') || 'en';
  });

  useEffect(() => {
    localStorage.setItem('deepguard_lang', lang);
  }, [lang]);

  const t = (key) => {
    return translations[lang]?.[key] || translations['en']?.[key] || key;
  };

  const cycleLang = () => {
    const idx = LANG_ORDER.indexOf(lang);
    const next = LANG_ORDER[(idx + 1) % LANG_ORDER.length];
    setLang(next);
  };

  const nextLangLabel = () => {
    const idx = LANG_ORDER.indexOf(lang);
    const next = LANG_ORDER[(idx + 1) % LANG_ORDER.length];
    return LANG_LABELS[next];
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, cycleLang, nextLangLabel, t, LANG_ORDER, LANG_LABELS }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}

export default LanguageContext;
